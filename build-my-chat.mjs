import { readFileSync, writeFileSync } from 'node:fs';
const assets = {};
for (const [name, type] of [['index.html', 'text/html; charset=utf-8'], ['app.js', 'text/javascript; charset=utf-8'], ['style.css', 'text/css; charset=utf-8']]) {
  assets[name] = { type, body: readFileSync(new URL('./functions/_lib/my-chat-ui/' + name, import.meta.url), 'utf8') };
}
writeFileSync(new URL('./functions/_lib/my-chat-assets.js', import.meta.url), '// Generated by build-my-chat.mjs. Served only after authentication. No secrets.\nexport const assets = ' + JSON.stringify(assets) + ';\n');
